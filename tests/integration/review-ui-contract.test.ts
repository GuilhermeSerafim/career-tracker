import { afterAll, beforeAll, expect, it } from 'vitest';
import { syntheticCareerApi } from '../helpers/synthetic-career';
import { seedReview } from '../helpers/review-scenario';
import { randomUUID } from 'node:crypto';
let api: Awaited<ReturnType<typeof syntheticCareerApi>>;
beforeAll(async () => { api = await syntheticCareerApi(); });
afterAll(async () => { await api?.close(); });
it('provides nonbinding preview, immutable selected Markdown and strict authenticated read boundaries', async () => {
  await seedReview(api);
  const list = await api.request('/api/v1/batches', { headers: api.headers });
  const id = list.json.items[0].id;
  const before = await api.auditCount();
  const detail = await api.request(`/api/v1/batches/${id}`, { headers: api.headers });
  expect(detail.json.preview?.eligiblePopulationIds).toHaveLength(30);
  expect(await api.auditCount()).toBe(before);
  const closed = await api.post({ operation: 'close_review', batch: { id, expectedVersion: detail.json.batch.version }, narrative: '<script>alert(1)</script> [x](javascript:alert(1))', decisions: ['Acompanhar'] });
  expect(closed.status).toBe(201);
  const review = await api.request(`/api/v1/reviews/${closed.json.reviewId}`, { headers: api.headers });
  expect(review.json.version.snapshot.metrics).toEqual(detail.json.preview.metrics);
  const audit = await api.auditCount();
  const markdown = await api.request(`/api/v1/reviews/${closed.json.reviewId}?format=markdown`, { headers: api.headers });
  expect(markdown.status).toBe(200); expect(markdown.headers['content-type']).toContain('text/markdown');
  expect(markdown.text).toContain('30'); expect(markdown.text).not.toContain('<script>'); expect(markdown.text).not.toContain('[x](javascript:');
  expect(await api.auditCount()).toBe(audit);
  expect((await api.request(`/api/v1/reviews/${closed.json.reviewId}?format=wrong`, { headers: api.headers })).status).toBe(400);
  expect((await api.request(`/api/v1/reviews/${closed.json.reviewId}?format=markdown`)).status).toBe(401);
});
it('rectifies only explicit eligibility while preserving the captured set and original snapshot', async () => {
  const list = await api.request('/api/v1/batches', { headers: api.headers }); const id = list.json.items[0].id;
  const before = (await api.request(`/api/v1/batches/${id}`, { headers: api.headers })).json;
  const original = (await api.request(`/api/v1/reviews/${before.versions[0].id}`, { headers: api.headers })).json.version;
  const member = original.populationIds[0];
  const proof = () => ({ clientId: randomUUID(), kind: 'relato_usuario', originalText: 'Correção fictícia.', source: null, occurredDate: null, privateRef: null, localRef: null });
  expect((await api.post({ operation: 'invalidate_submission', application: { id: member, expectedVersion: 1 }, affectedBatches: [{ id, expectedVersion: before.batch.version }], reason: 'Confirmação inválida fictícia', evidence: proof() })).status).toBe(200);
  const pending = (await api.request(`/api/v1/batches/${id}`, { headers: api.headers })).json;
  expect(pending.members).toHaveLength(30); expect(pending.rectificationPreview.eligiblePopulationIds).toHaveLength(29);
  const result = await api.post({ operation: 'revise_review', batch: { id, expectedVersion: pending.batch.version }, predecessorId: original.id, type: 'rectification', reason: 'Corrigir denominador', evidence: proof(), narrative: 'Retificação explícita', decisions: [] });
  expect(result.status).toBe(201);
  const revised = (await api.request(`/api/v1/reviews/${result.json.reviewId}`, { headers: api.headers })).json.version;
  expect(revised.populationIds).toEqual(original.populationIds); expect(revised.predecessorId).toBe(original.id); expect(revised.snapshot.metrics).toEqual(pending.rectificationPreview.metrics);
  expect((await api.request(`/api/v1/reviews/${original.id}`, { headers: api.headers })).json.version).toEqual(original);
});
